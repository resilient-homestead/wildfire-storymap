"""Write the story text into index.html as plain HTML.

The live page is built in the browser by js/story.js from
data/chapters.json, so a crawler that does not run JavaScript (Bing, link
preview bots, most AI crawlers) fetches an empty shell. This script renders
the same text - section headings, chapter titles and copy, image alt text
and captions, footer links - into index.html between the STATIC-STORY
markers, so the words are in the file itself.

Visitors never see this copy: an inline script in <head> adds the "js"
class to <html> before first paint and css/style.css hides #static-story
under it. With JavaScript off it is the page. The text is the same either
way, which is what keeps this progressive enhancement rather than cloaking.

It also writes sitemap.xml: the page URL plus every story image (Google's
image-sitemap extension - only <image:loc> is read; caption/title were
deprecated in 2022, and the captions reach Google through the HTML above).
<lastmod> moves to today ONLY when the static story actually changed, and
is otherwise carried over - a lastmod that changes on every run teaches
Google to ignore it.

Run after every change to data/chapters.json (or to SECTION_LABELS in
js/story.js):

    python tools/prerender.py           rewrite index.html + sitemap.xml
    python tools/prerender.py --check   exit 1 if either is stale
"""
import datetime
import html
import json
import re
import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "index.html"
SITEMAP = ROOT / "sitemap.xml"
CHAPTERS = ROOT / "data" / "chapters.json"
STORY_JS = ROOT / "js" / "story.js"

# Must match <link rel="canonical"> in index.html.
SITE_URL = "https://resilient-homestead.github.io/wildfire-storymap/"

START = "<!-- STATIC-STORY:START (generated by tools/prerender.py - do not edit by hand) -->"
END = "<!-- STATIC-STORY:END -->"
HERO_START = "<!-- HERO:START (generated by tools/prerender.py - do not edit by hand) -->"
HERO_END = "<!-- HERO:END -->"

PAUSE_ICON = ('<svg viewBox="0 0 24 24" aria-hidden="true"><rect x="6" y="5" width="4" height="14" rx="1"/>'
              '<rect x="14" y="5" width="4" height="14" rx="1"/></svg>')
PLAY_ICON = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M8 5.5v13l11-6.5z"/></svg>'


def poster_variants(poster):
    """[(path, width)] for the poster and its optional smaller siblings.

    media/hero-poster.webp -> media/hero-poster-800.webp and -1280.webp, each
    used if the file exists. Recreate them whenever the poster changes:
    800 px covers a 412 px phone at 1.75x (Lighthouse's Moto G), 1280 px a
    phone at 3x (iPhones) - without it those fell through to the 1920 px one.
    """
    p = Path(poster)
    out = []
    for w in (800, 1280):
        small = p.with_name(f"{p.stem}-{w}{p.suffix}")
        if (ROOT / small).exists():
            out.append((small.as_posix(), w))
    from PIL import Image  # only needed here
    with Image.open(ROOT / poster) as im:
        out.append((poster, im.width))
    return out


def poster_img_attrs(poster):
    """src/srcset/sizes for the hero poster - also used for its preload."""
    variants = poster_variants(poster)
    srcset = ", ".join(f"{quote(p)} {w}w" for p, w in variants)
    return f'src="{quote(poster)}" srcset="{srcset}" sizes="100vw"'


def render_hero(doc):
    """The title screen as real HTML inside #story.

    It is the page's LCP element. Built by story.js it could not paint until
    story.js and chapters.json had downloaded and the WHOLE page had been
    constructed - PageSpeed measured 6.9 s of render delay on mobile. Shipped
    here it paints with the first HTML; renderHeroChapter() sees
    data-prerendered and adopts it instead of rebuilding it.

    Must stay structurally identical to renderHeroChapter()'s markup (same
    classes, same nesting) - that function's CSS and its play/pause wiring
    depend on it. Three deliberate differences: the <video> has no autoplay
    and preload="none", so not a byte of the background video is fetched
    before story.js starts it after the window load event (and never for
    prefers-reduced-motion or Save-Data); its poster is a responsive
    <img class="hero-bg-poster"> under it instead of a poster attribute (see
    below); and the hero's icon is omitted - .hero-content .icon is
    display:none.
    """
    hero = next((c for c in doc["chapters"] if c.get("isTitleScreen")), None)
    if not hero:
        return f"{HERO_START}\n  {HERO_END}"
    bg = hero.get("backgroundVideo") or {}
    poster = bg.get("poster") or (hero.get("image") or {}).get("src") or ""
    out = [HERO_START,
           f'  <section class="chapter hero" id="{html.escape(hero["id"])}" '
           f'data-map-position="{html.escape(hero.get("mapPosition") or "none")}" data-prerendered="true">']
    if bg.get("src"):
        # The poster is a responsive <img> under the video rather than the
        # video's poster attribute, which cannot vary by screen: a phone
        # gets the -800 copy (~78 KB) instead of the 1920 px one (~240 KB).
        # It is the first screen's largest image, and every byte requested
        # before first paint counts against LCP on a slow connection. The
        # video has no poster of its own, so it stays transparent - showing
        # this image - until it actually plays.
        out += ['    <div class="hero-bg hero-bg-video">']
        if poster:
            out.append(f'      <img class="hero-bg-poster" {poster_img_attrs(poster)} alt="" '
                       'fetchpriority="high" decoding="async" />')
        out += ['      <video class="hero-bg-media" muted loop playsinline preload="none" aria-hidden="true">',
                f'        <source src="{quote(bg["src"])}" type="video/mp4" />',
                "      </video>",
                '      <div class="hero-bg-overlay"></div>',
                '      <button type="button" class="hero-video-toggle" aria-label="Play background video" '
                f'data-tip="Click to play the background video" data-tip-pos="left">{PLAY_ICON}</button>',
                "    </div>"]
    else:
        style = f' style="background-image: url(\'{quote(poster)}\')"' if poster else ""
        out += [f'    <div class="hero-bg"{style}>', '      <div class="hero-bg-overlay"></div>', "    </div>"]
    out.append('    <div class="hero-content">')
    if hero.get("eyebrow"):
        out.append(f'      <p class="eyebrow">{hero["eyebrow"]}</p>')
    # Title and description are authored HTML, inserted as-is exactly like
    # renderHeroChapter() does.
    out.append(f'      <h1>{hero.get("title", "")}</h1>')
    if hero.get("description"):
        out.append(f'      <p class="hero-lede">{hero["description"]}</p>')
    out += ['      <div class="scroll-cue">Scroll to begin<span class="scroll-cue-arrow" aria-hidden="true"></span></div>',
            "    </div>", "  </section>", f"  {HERO_END}"]
    return "\n".join(out)


def section_labels():
    """SECTION_LABELS from js/story.js, so the nav and this copy cannot drift."""
    src = STORY_JS.read_text(encoding="utf-8")
    block = re.search(r"const SECTION_LABELS = \{(.*?)\};", src, re.S)
    if not block:
        sys.exit("SECTION_LABELS not found in js/story.js")
    return dict(re.findall(r'(section\d+):\s*"([^"]+)"', block.group(1)))


def section_id(chapter):
    # Mirrors sectionIdFor() in js/story.js.
    m = re.match(r"(section\d+)-", chapter.get("id", ""))
    return m.group(1) if m else "section1"


def media_html(item, pad):
    caption = item.get("caption") or ""
    if item.get("type") == "video":
        url = item.get("youtubeUrl") or (item.get("src") if "youtu" in (item.get("src") or "") else None)
        if not url:
            return ""
        label = html.escape(caption or item.get("alt") or "Video")
        return f'{pad}<p class="static-video">Video: <a href="{html.escape(url)}">{label}</a></p>\n'
    src = item.get("src")
    if not src:
        return ""
    # loading="lazy": an image inside a display:none ancestor is never
    # fetched, so visitors with JavaScript do not download any of these.
    out = (f'{pad}<figure>\n'
           f'{pad}  <img src="{quote(src)}" alt="{html.escape(item.get("alt") or "")}" loading="lazy" decoding="async" />\n')
    if caption:
        out += f"{pad}  <figcaption>{html.escape(caption)}</figcaption>\n"
    return out + f"{pad}</figure>\n"


def render(doc):
    labels = section_labels()
    chapters = doc["chapters"]
    out = [START, '<main id="static-story" class="static-story">']

    # The title screen is not repeated here: render_hero() puts the real one
    # in #story, visible with or without JavaScript, and a second copy would
    # read to a crawler as the intro said twice.
    hero = next((c for c in chapters if c.get("isTitleScreen")), None)

    current = None
    for ch in chapters:
        if ch is hero:
            continue
        sid = section_id(ch)
        if sid != current:
            if current is not None:
                out.append("  </section>")
            current = sid
            out.append(f'  <section aria-label="{html.escape(labels.get(sid, sid))}">')
            out.append(f'    <h2>{html.escape(labels.get(sid, sid))}</h2>')
        out.append("    <article>")
        if ch.get("title"):
            out.append(f'      <h3>{html.escape(ch["title"])}</h3>')
        if ch.get("description"):
            # Chapter copy is authored HTML (links, key-lines, pro-tips) and
            # goes in as-is, exactly as story.js renders it - except that any
            # <img> in it is forced lazy. Hidden or not, an eager image is
            # downloaded, and this whole block is hidden for JS visitors.
            body = re.sub(r"<img (?![^>]*\bloading=)", '<img loading="lazy" ', ch["description"])
            out.append(f"      {body}")
        media = "".join(media_html(m, "      ") for m in ch.get("media") or [])
        if media:
            out.append(media.rstrip("\n"))
        out.append("    </article>")
    if current is not None:
        out.append("  </section>")

    foot = doc.get("footer") or {}
    if foot.get("links"):
        out.append('  <nav class="static-links" aria-label="Resources">')
        if foot.get("title"):
            out.append(f'    <h2>{html.escape(foot["title"])}</h2>')
        if foot.get("text"):
            out.append(f'    <p>{html.escape(foot["text"])}</p>')
        out.append("    <ul>")
        for link in foot["links"]:
            out.append(f'      <li><a href="{html.escape(link["url"])}">{html.escape(link["label"])}</a></li>')
        out.append("    </ul>")
        out.append("  </nav>")

    out += ["</main>", END]
    return "\n".join(out)


def story_images(doc):
    """Every image the story shows, in page order, without repeats."""
    seen = []
    for ch in doc["chapters"]:
        srcs = [m.get("src") for m in ch.get("media") or [] if m.get("type") != "video"]
        srcs += re.findall(r'<img[^>]*\bsrc="([^"]+)"', ch.get("description") or "")
        for src in srcs:
            if src and not src.startswith("http") and src not in seen:
                seen.append(src)
    return seen


def render_sitemap(doc, lastmod):
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"',
           '        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">',
           "  <url>",
           f"    <loc>{SITE_URL}</loc>",
           f"    <lastmod>{lastmod}</lastmod>"]
    for src in story_images(doc):
        out.append(f"    <image:image><image:loc>{html.escape(SITE_URL + quote(src))}</image:loc></image:image>")
    out += ["  </url>", "</urlset>", ""]
    return "\n".join(out)


def current_lastmod():
    if SITEMAP.exists():
        m = re.search(r"<lastmod>([^<]+)</lastmod>", SITEMAP.read_text(encoding="utf-8"))
        if m:
            return m.group(1)
    return None


def main():
    doc = json.loads(CHAPTERS.read_text(encoding="utf-8"))
    page = INDEX.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START) + ".*?" + re.escape(END), re.S)
    hero_pattern = re.compile(re.escape(HERO_START) + ".*?" + re.escape(HERO_END), re.S)
    if not pattern.search(page):
        sys.exit("STATIC-STORY markers not found in index.html")
    if not hero_pattern.search(page):
        sys.exit("HERO markers not found in index.html (they belong inside <div id=\"story\">)")
    fresh = pattern.sub(lambda _: render(doc), page)
    fresh = hero_pattern.sub(lambda _: render_hero(doc), fresh)

    story_changed = fresh != page
    old_map = SITEMAP.read_text(encoding="utf-8") if SITEMAP.exists() else ""
    lastmod = current_lastmod()
    if story_changed or not lastmod:
        lastmod = datetime.date.today().isoformat()
    fresh_map = render_sitemap(doc, lastmod)

    if "--check" in sys.argv:
        stale = [name for name, ok in (("index.html", not story_changed),
                                       ("sitemap.xml", fresh_map == old_map)) if not ok]
        if stale:
            sys.exit(f"{' and '.join(stale)} out of date - run: python tools/prerender.py")
        print("index.html and sitemap.xml are up to date")
        return
    for path, new, old in ((INDEX, fresh, page), (SITEMAP, fresh_map, old_map)):
        if new != old:
            path.write_text(new, encoding="utf-8", newline="\n")
            print(f"{path.name} updated")
        else:
            print(f"{path.name} already up to date")


if __name__ == "__main__":
    main()
